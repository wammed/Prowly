//! AI Pull Request draft title and body generation.

use crate::ai::{AiClient, AiError, AiPrompt};
use crate::i18n::Language;

/// Generated Pull Request draft containing title and Markdown description.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GeneratedPrDraft {
    pub title: String,
    pub body: String,
}

/// Generate a Pull Request draft from branch diff and branch name.
pub async fn generate_pr_draft(
    branch_name: &str,
    diff_summary: &str,
    client: &dyn AiClient,
    lang: Language,
) -> Result<GeneratedPrDraft, AiError> {
    let system = match lang {
        Language::Ja => {
            "あなたはオープンソース開発をリードする熟練テックリードです。\n\
与えられたブランチ名とGit差分から、魅力的でわかりやすいPull Requestのタイトルと本文(Markdown)を生成してください。\n\
フォーマットルール:\n\
- 1行目: PRタイトル (例: feat(auth): add OAuth2 token refresh support)\n\
- 2行目: 空行\n\
- 3行目以降: PR本文 (## 概要, ## 変更点, ## 影響範囲・テスト内容)"
        }
        Language::En => {
            "You are a skilled tech lead. Generate a clear Pull Request title and Markdown body from the provided branch and diff.\n\
Format rules:\n\
- Line 1: PR title (e.g. feat(auth): add OAuth2 token refresh support)\n\
- Line 2: Empty line\n\
- Line 3+: PR body in Markdown (## Overview, ## Key Changes, ## Testing & Verification)"
        }
    };

    let user = format!(
        "Branch: {}\n\nDiff Summary:\n{}",
        branch_name,
        diff_summary.chars().take(4000).collect::<String>()
    );

    let prompt = AiPrompt::system_and_user(system, user);
    let res = client.complete(&prompt).await?;
    let content = res.content.trim();

    let mut lines = content.lines();
    let title = lines
        .next()
        .map(|s| s.trim().trim_start_matches('#').trim().to_string())
        .unwrap_or_else(|| format!("PR: {}", branch_name));

    // Skip empty lines to get body
    let body_lines: Vec<&str> = lines.collect();
    let body = body_lines.join("\n").trim().to_string();

    Ok(GeneratedPrDraft {
        title,
        body: if body.is_empty() {
            "## Summary\nPull request automatically generated by Prowly AI.".to_string()
        } else {
            body
        },
    })
}
