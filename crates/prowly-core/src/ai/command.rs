//! AI Natural Language to Git command assistant.

use crate::ai::{AiClient, AiError, AiPrompt};
use crate::i18n::Language;

/// Risk level of an executed Git command.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CommandRiskLevel {
    Safe,
    Caution,
    Dangerous,
}

/// Suggested Git command with explanation and safety rating.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SuggestedGitCommand {
    pub command: String,
    pub explanation: String,
    pub risk_level: CommandRiskLevel,
}

/// Translate natural language request into a recommended Git command.
pub async fn translate_natural_language_to_git(
    user_request: &str,
    current_branch: &str,
    client: &dyn AiClient,
    lang: Language,
) -> Result<SuggestedGitCommand, AiError> {
    let system = match lang {
        Language::Ja => {
            "あなたはGitの最高峰エンジニアです。開発者の自然言語リクエストを正確なGitコマンドに翻訳してください。\n\
回答フォーマット:\n\
Line 1: 実行すべきGitコマンド (例: git reset --soft HEAD~1)\n\
Line 2: [Safe | Caution | Dangerous] のいずれか1単語\n\
Line 3以降: コマンドの動作と理由の簡潔な解説"
        }
        Language::En => {
            "You are a Git expert. Translate the developer's natural language request into the exact Git command.\n\
Format:\n\
Line 1: The Git command (e.g. git reset --soft HEAD~1)\n\
Line 2: One word [Safe | Caution | Dangerous]\n\
Line 3+: Brief explanation of the command and consequences"
        }
    };

    let user = format!(
        "Current Branch: {}\nRequest: {}",
        current_branch, user_request
    );
    let prompt = AiPrompt::system_and_user(system, user);
    let res = client.complete(&prompt).await?;
    let content = res.content.trim();

    let mut lines = content.lines();
    let command = lines.next().unwrap_or("git status").trim().to_string();
    let risk_str = lines.next().unwrap_or("Safe").trim().to_lowercase();
    let risk_level = if risk_str.contains("danger") {
        CommandRiskLevel::Dangerous
    } else if risk_str.contains("caution") {
        CommandRiskLevel::Caution
    } else {
        CommandRiskLevel::Safe
    };

    let explanation_lines: Vec<&str> = lines.collect();
    let explanation = explanation_lines.join("\n").trim().to_string();

    Ok(SuggestedGitCommand {
        command,
        explanation: if explanation.is_empty() {
            "Command generated by Prowly AI co-pilot.".to_string()
        } else {
            explanation
        },
        risk_level,
    })
}
